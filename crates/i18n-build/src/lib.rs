//! Build-time i18n dictionary generator.
//!
//! Parses the controlled-subset TOML dictionaries under the top-level
//! `i18n/` directory and emits a Rust source module with a compiled-in lookup
//! table, language detection (environment variable, English fallback) and a
//! `t(key)` lookup. std-only; intended to be used as a build-dependency.
//!
//! Supported dictionary shape (only `en` and `zh`):
//!
//! ```toml
//! [menu.file]
//! en = "File"
//! zh = "文件"
//! ```

struct Entry {
    key: String,
    en: String,
    zh: String,
}

fn parse_quoted(s: &str) -> String {
    let Some(inner) = s.strip_prefix('"').and_then(|s| s.strip_suffix('"')) else {
        panic!("i18n: value must be a double-quoted string: {s}");
    };
    inner.replace("\\\"", "\"").replace("\\\\", "\\")
}

fn parse(toml: &str) -> Vec<Entry> {
    let mut entries: Vec<Entry> = Vec::new();
    let mut cur: Option<Entry> = None;

    for raw in toml.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(k) = line.strip_prefix('[').and_then(|s| s.strip_suffix(']')) {
            if let Some(e) = cur.take() {
                entries.push(e);
            }
            cur = Some(Entry { key: k.trim().to_string(), en: String::new(), zh: String::new() });
            continue;
        }
        let Some((k, v)) = line.split_once('=') else {
            panic!("i18n: malformed line: {line}");
        };
        let k = k.trim();
        let v = parse_quoted(v.trim());
        let e = cur.as_mut().expect("i18n: value appears before its [key]");
        match k {
            "en" => e.en = v,
            "zh" => e.zh = v,
            other => panic!("i18n: unsupported language `{other}` (only en/zh)"),
        }
    }
    if let Some(e) = cur {
        entries.push(e);
    }

    for e in &entries {
        if e.en.is_empty() {
            panic!("i18n: key `{}` is missing its `en` translation", e.key);
        }
    }
    // Reject duplicate keys so a typo cannot silently shadow an entry.
    for (i, a) in entries.iter().enumerate() {
        if let Some(b) = entries.iter().skip(i + 1).find(|b| b.key == a.key) {
            panic!("i18n: duplicate key `{}`", b.key);
        }
    }
    entries
}

/// Generate the Rust source module for the given dictionary TOML text.
pub fn generate(toml: &str) -> String {
    let entries = parse(toml);
    let mut out = String::new();

    out.push_str("// Generated by i18n-build from the top-level i18n/*.toml. Do not edit.\n\n");
    out.push_str("#[derive(Clone, Copy, PartialEq, Eq, Debug)]\npub enum Lang { En, Zh }\n\n");

    out.push_str(
        r#"pub fn detect_lang() -> Lang {
    static LANG: std::sync::OnceLock<Lang> = std::sync::OnceLock::new();
    *LANG.get_or_init(|| {
        // Explicit override wins, then the system locale; anything that is
        // not a Chinese variant falls back to English.
        for var in ["TC_LANGUAGE", "LANG", "LC_ALL"] {
            if let Ok(v) = std::env::var(var) {
                let v = v.trim().to_ascii_lowercase();
                if v.is_empty() {
                    continue;
                }
                return if v.starts_with("zh") { Lang::Zh } else { Lang::En };
            }
        }
        Lang::En
    })
}

"#,
    );

    out.push_str("const TABLE: &[(&str, &str, &str)] = &[\n");
    for e in &entries {
        out.push_str(&format!("    ({:?}, {:?}, {:?}),\n", e.key, e.en, e.zh));
    }
    out.push_str("];\n\n");

    out.push_str(
        r#"/// Look up a message for the active language. Unknown keys return the key
/// itself; a missing `zh` entry falls back to `en`.
pub fn t(key: &str) -> &str {
    t_lang(detect_lang(), key)
}

/// Look up a message for an explicit language (mainly for tests).
pub fn t_lang(lang: Lang, key: &str) -> &str {
    let Some((_, en, zh)) = TABLE.iter().find(|(k, _, _)| *k == key) else {
        return key;
    };
    match lang {
        Lang::En => en,
        Lang::Zh => {
            if zh.is_empty() { en } else { zh }
        }
    }
}
"#,
    );

    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_entries_and_generates_lookup() {
        let src =
            "[menu.file]\nen = \"File\"\nzh = \"文件\"\n\n[repl.bye]\nen = \"Bye\"\nzh = \"\"\n";
        let code = generate(src);
        assert!(code.contains("\"menu.file\""));
        assert!(code.contains("\"文件\""));
    }

    #[test]
    #[should_panic(expected = "missing its `en`")]
    fn rejects_missing_english() {
        generate("[x]\nzh = \"甲\"\n");
    }

    #[test]
    #[should_panic(expected = "unsupported language")]
    fn rejects_other_language() {
        generate("[x]\nen = \"X\"\nde = \"X\"\n");
    }

    #[test]
    #[should_panic(expected = "duplicate key")]
    fn rejects_duplicate_key() {
        generate("[x]\nen = \"A\"\n\n[x]\nen = \"B\"\n");
    }
}
